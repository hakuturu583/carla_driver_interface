"""Packaging a policy as an alpasim driver: a Docker image and the wizard's config.

alpasim runs its driver as a container its wizard starts (``services.driver`` in the
wizard's Hydra config: an image, and a command with a ``{port}`` the wizard fills in),
and its runtime talks to it over ``egodriver.EgodriverService``. A policy served by
this package speaks that contract already; what it needs to drop into alpasim is

* an image that serves it -- :func:`write_build_context` / :func:`build_image`
  (``carla-driver-interface alpasim build-image``): the policy and this package
  installed with pip on a Python base image, serving in ``alpasim`` mode by default;
* a driver config group for the wizard -- :func:`write_wizard_config`
  (``carla-driver-interface alpasim wizard-config``): ``driver=<name>``, found through
  ``hydra.searchpath``, runs that image as alpasim's driver service.

Nothing here imports alpasim or Docker's SDK: the image is described by a generated
Dockerfile and built by the ``docker`` CLI, and the config is plain YAML text.
"""

