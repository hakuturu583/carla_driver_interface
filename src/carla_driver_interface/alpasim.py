#: The policy an image serves when its command names none (``serve --policy``).
POLICY_ENV = "CARLA_DRIVER_INTERFACE_POLICY"
#: Keyword arguments for that policy, as a JSON object.
POLICY_ARGS_ENV = "CARLA_DRIVER_INTERFACE_POLICY_ARGS"

#: Any image with ``python``, ``pip`` and ``bash`` (alpasim runs ``bash -c``) works.
DEFAULT_BASE_IMAGE = "python:3.12-slim"
#: The port an image serves on when run by itself; the wizard passes its own.
DEFAULT_PORT = 50051

#: Where alpasim mounts the run's log directory in its driver container.
ALPASIM_OUTPUT_DIR = "/mnt/output"

#: Left out of a local package copied into the build context.
_IGNORED = (
    ".git",
    ".venv",
    "venv",
    "__pycache__",
    "*.pyc",
    ".mypy_cache",
    ".pytest_cache",
    ".ruff_cache",
    ".tox",
    "node_modules",
)


def parse_policy_args(items: Sequence[str]) -> Dict[str, Any]:
    """``["key=value", ...]`` to keyword arguments; a value is JSON when it parses.

    ``speed=8.5`` gives a float and ``name=fast`` a string; quote a string that
    would parse as JSON (``name='"8"'``).
    """
    kwargs: Dict[str, Any] = {}
    for item in items:
        key, sep, raw = item.partition("=")
        if not sep or not key.isidentifier():
            raise ValueError(f"policy argument {item!r} is not key=value")
        try:
            kwargs[key] = json.loads(raw)
        except json.JSONDecodeError:
            kwargs[key] = raw
    return kwargs


# -- the image -------------------------------------------------------------------


@dataclass
class ImageSpec:
    """What goes into a driver image."""

    #: Default policy (``serve --policy``), baked in as :data:`POLICY_ENV`.
    policy: str = "route_follower"
    policy_args: Dict[str, Any] = field(default_factory=dict)
    #: pip requirements for the policy: names (``my-policy==1.2``), URLs, or local
    #: paths (a project directory or a wheel), which are copied into the context.
    install: List[str] = field(default_factory=list)
    #: How to install this package; defaults to the running version from PyPI. A
    #: local path (this checkout, say) is copied in like any other.
    carla_driver_interface: Optional[str] = None
    base_image: str = DEFAULT_BASE_IMAGE
    #: Debian packages to install first (``libgl1`` for OpenCV, say).
    apt_packages: List[str] = field(default_factory=list)
    #: Import the policy's module at build time, so a misspelt policy fails the
    #: build rather than the first rollout.
    check_policy: bool = True

    def requirement_for_self(self) -> str:
        return self.carla_driver_interface or f"carla-driver-interface=={__version__}"


def _is_local(requirement: str) -> bool:
    return Path(requirement).expanduser().exists()


def render_dockerfile(spec: ImageSpec, requirements: Sequence[str]) -> str:
    """The Dockerfile for *spec*, installing *requirements* (context-relative paths
    for local packages, as :func:`write_build_context` lays them out)."""
    lines = [
        f"# Generated by carla-driver-interface {__version__}"
        " (`carla-driver-interface alpasim build-image`).",
        f"FROM {spec.base_image}",
        "",
        "ENV PYTHONUNBUFFERED=1 PIP_NO_CACHE_DIR=1 PIP_DISABLE_PIP_VERSION_CHECK=1",
    ]
    if spec.apt_packages:
        packages = " ".join(shlex.quote(p) for p in spec.apt_packages)
        lines += [
            "RUN apt-get update \\",
            f"    && apt-get install -y --no-install-recommends {packages} \\",
            "    && rm -rf /var/lib/apt/lists/*",
        ]
    lines += [
        "COPY packages/ /opt/carla-driver-interface/packages/",
        "WORKDIR /opt/carla-driver-interface/packages",
        # One resolution for everything, so the policy's pins and ours must agree.
        "RUN python -m pip install " + " ".join(shlex.quote(r) for r in requirements),
        "WORKDIR /",
        f"ENV {POLICY_ENV}={json.dumps(spec.policy)}",
        f"ENV {POLICY_ARGS_ENV}={json.dumps(json.dumps(spec.policy_args))}",
        "RUN carla-driver-interface --help > /dev/null",
    ]
    if spec.check_policy and ":" in spec.policy:
        module, _, attribute = spec.policy.partition(":")
        check = (
            "import importlib; getattr(importlib.import_module("
            f"{json.dumps(module)}), {json.dumps(attribute)})"
        )
        lines.append(f"RUN python -c {shlex.quote(check)}")
    lines += [
        f"EXPOSE {DEFAULT_PORT}",
        # Run by itself, the image serves alpasim; the wizard replaces the command.
        "CMD "
        + json.dumps(
            [
                "carla-driver-interface",
                "serve",
                "--mode",
                "alpasim",
                "--host",
                "0.0.0.0",
                "--port",
                str(DEFAULT_PORT),
            ]
        ),
        "",
    ]
    return "\n".join(lines)


def write_build_context(spec: ImageSpec, context_dir: Path) -> Path:
    """Lay out a Docker build context for *spec* in *context_dir*; returns the
    Dockerfile. Local packages are copied under ``packages/``."""
    context_dir = Path(context_dir)
    packages = context_dir / "packages"
    if packages.exists():
        shutil.rmtree(packages)
    packages.mkdir(parents=True)

    requirements: List[str] = []
    for index, requirement in enumerate([spec.requirement_for_self(), *spec.install]):
        if not _is_local(requirement):
            requirements.append(requirement)
            continue
        source = Path(requirement).expanduser().resolve()
        target = packages / f"{index:02d}-{source.name}"
        if source.is_dir():
            shutil.copytree(source, target, ignore=shutil.ignore_patterns(*_IGNORED))
            requirements.append(f"./{target.name}")
        else:
            # A wheel's name is its metadata; keep it under a directory instead.
            target.mkdir()
            shutil.copy2(source, target / source.name)
            requirements.append(f"./{target.name}/{source.name}")

    dockerfile = context_dir / "Dockerfile"
    dockerfile.write_text(render_dockerfile(spec, requirements))
    return dockerfile


def build_image(
    spec: ImageSpec,
    tag: str,
    context_dir: Path,
    docker: str = "docker",
    extra_args: Sequence[str] = (),
) -> None:
    """Write the build context for *spec* and build it as *tag* with ``docker build``.

    Raises:
        FileNotFoundError: *docker* is not on ``PATH``.
        subprocess.CalledProcessError: the build failed.
    """
    if shutil.which(docker) is None:
        raise FileNotFoundError(f"{docker!r} not found on PATH")
    write_build_context(spec, context_dir)
    subprocess.run(
        [docker, "build", "--tag", tag, *extra_args, str(context_dir)], check=True
    )


